-- Брошенные корзины: момент отправки дожима (см. код-ревью фичи Abandoned).
-- Флаг reminded (boolean) уже существовал, но без метки времени было не отличить
-- свежий дожим от старого (например, для 7-дневного окна browse follow-up).
-- Джоба ставит reminded_at только по финальному исходу (доставлено / дефинитивный скип),
-- транзиентные ошибки ретраятся следующим тиком.
alter table public.invoices
    add column if not exists reminded_at timestamptz;
